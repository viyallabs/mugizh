// Command packsum prints or updates the checksums of a country pack (S-099).
//
//	packsum <pack-dir>...          rewrite pack.checksums in each pack.yaml
//	packsum -check <pack-dir>...   exit 1 if any checksum is stale (CI)
//
// Changing a pack file needs the approver named in docs/arch/country-pack-model.md
// section 2; regenerating checksums does not replace that approval.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"gitlab.com/viyallabs/mugizh/backend/internal/modules/config"
)

func main() {
	check := flag.Bool("check", false, "verify only; exit 1 if a checksum is stale")
	flag.Parse()
	if flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "usage: packsum [-check] <pack-dir>...")
		os.Exit(2)
	}
	failed := false
	for _, dir := range flag.Args() {
		stale, err := run(dir, *check)
		if err != nil {
			fmt.Fprintf(os.Stderr, "packsum: %s: %v\n", dir, err)
			os.Exit(2)
		}
		failed = failed || stale
	}
	if failed {
		os.Exit(1)
	}
}

func run(dir string, check bool) (stale bool, err error) {
	sums, err := config.ComputeChecksums(dir)
	if err != nil {
		return false, err
	}
	path := filepath.Join(dir, config.ManifestFile)
	data, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	out, err := replaceChecksums(string(data), sums)
	if err != nil {
		return false, err
	}
	for _, n := range sortedKeys(sums) {
		fmt.Printf("%s  %s/%s\n", sums[n], filepath.ToSlash(dir), n)
	}
	if out == string(data) {
		return false, nil
	}
	if check {
		fmt.Fprintf(os.Stderr, "packsum: %s: checksums are stale\n", path)
		return true, nil
	}
	// path is the pack manifest named by the developer on the command line (a repo file);
	// this tool never runs on untrusted input or in a server.
	return false, os.WriteFile(filepath.Clean(path), []byte(out), 0o600) // #nosec G703 G306 -- developer CLI on a repo file
}

func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

var reChecksumsKey = regexp.MustCompile(`^(\s+)checksums:.*$`)

// replaceChecksums rewrites the `checksums:` entry of the pack section as a block map,
// keeping every other line (and comment) untouched.
func replaceChecksums(text string, sums map[string]string) (string, error) {
	nl := "\n"
	if strings.Contains(text, "\r\n") {
		nl = "\r\n"
	}
	lines := strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n")
	for i, l := range lines {
		m := reChecksumsKey.FindStringSubmatch(l)
		if m == nil {
			continue
		}
		indent := m[1]
		j := i + 1
		for j < len(lines) && strings.HasPrefix(lines[j], indent+"  ") {
			j++
		}
		block := []string{indent + "checksums:                        # generated by cmd/packsum; do not edit by hand"}
		for _, n := range sortedKeys(sums) {
			block = append(block, fmt.Sprintf("%s  %s: %s", indent, n, sums[n]))
		}
		res := append(append(append([]string{}, lines[:i]...), block...), lines[j:]...)
		return strings.Join(res, nl), nil
	}
	return "", fmt.Errorf("no checksums key found in manifest")
}
